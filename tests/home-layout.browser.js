// Run await runHomeLayoutTests() in the fixture's console or collaborative preview.
window.runHomeLayoutTests = async () => {
  const results = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const settle = () => new Promise(resolve => setTimeout(resolve, 60));
  const root = () => document.querySelector('#hayase-home-layout').shadowRoot;
  root().getElementById('open').click();
  assert(root().querySelector('dialog').matches(':modal'), 'Customize opens a native modal');
  assert(document.getElementById('hayase-home-layout').getBoundingClientRect().right <= innerWidth, 'Customize trigger fits at the top right');
  assert(!root().querySelector('#release-settings, #release-options, a'), 'Modal contains no release-options or credits block');
  root().getElementById('close').click();
  assert(!root().querySelector('dialog').open, 'Close button dismisses the modal');
  const control = (id, action) => [...root().querySelectorAll('input,button')].find(node => node.dataset.id === id && node.dataset.action === action);
  root().getElementById('reset').click();
  await settle();
  const recent = document.getElementById('hayase-recent-episodes');
  const heading = [...document.querySelectorAll('div.cursor-pointer')].find(node => node.textContent.includes('Continue Watching'));
  const row = heading.nextElementSibling;
  control('plugin:recent-episodes', '1').click();
  await settle();
  assert(heading.nextElementSibling === row && row.nextElementSibling === recent, 'Moving keeps native headings and rows together');
  assert(root().querySelector('li').textContent.includes('Continue Watching'), 'Editor order follows page order');
  control('hayase:Continue Watching', 'show').click();
  await settle();
  assert(getComputedStyle(heading).display === 'none' && getComputedStyle(row).display === 'none', 'Hiding removes both native heading and content');
  control('plugin:recent-episodes', 'show').click();
  await settle();
  assert(getComputedStyle(recent).display === 'none' && document.getElementById('hayase-home-layout').isConnected, 'Editor stays available when all sections are hidden');
  const saved = JSON.parse(localStorage.getItem('home-layout-v1'));
  assert(saved.order[0] === 'hayase:Continue Watching' && saved.hidden.length === 2, 'Order and visibility are persisted');
  location.hash = '#/app/anime/21';
  dispatchEvent(new HashChangeEvent('hashchange'));
  await settle();
  assert(!document.getElementById('hayase-home-layout') && !document.getElementById('hayase-recent-episodes'), 'Leaving Home cleans up both plugin sections');
  assert(!heading.hasAttribute('data-hayase-home-hidden'), 'Leaving Home restores native visibility');
  location.hash = '#/app/home';
  dispatchEvent(new HashChangeEvent('hashchange'));
  await settle();
  assert(document.querySelectorAll('#hayase-home-layout').length === 1 && document.querySelectorAll('#hayase-recent-episodes').length === 1, 'Returning Home mounts exactly one editor and release panel');
  assert(getComputedStyle(heading).display === 'none', 'Returning Home reapplies saved visibility');
  root().getElementById('reset').click();
  await settle();
  assert(getComputedStyle(heading).display !== 'none' && !document.getElementById('hayase-recent-episodes').hasAttribute('data-hayase-home-hidden'), 'Reset restores all sections');
  assert(document.getElementById('hayase-recent-episodes').nextElementSibling === heading, 'Reset restores default order');
  // Simulate a section appearing after account/list data finishes loading.
  const dynamicHeading = document.createElement('div');
  dynamicHeading.className = 'cursor-pointer text-muted-foreground';
  dynamicHeading.innerHTML = '<div class="font-semibold text-lg">Your List</div>';
  const dynamicRow = document.createElement('div'); dynamicRow.className = 'overflow-x-scroll';
  const fragment = document.createDocumentFragment(); fragment.append(dynamicHeading, dynamicRow); heading.parentNode.append(fragment);
  await settle();
  assert(!!control('hayase:Your List', 'show'), 'Sections arriving later are discovered');
  dynamicHeading.remove(); dynamicRow.remove();
  await settle();
  assert(!control('hayase:Your List', 'show'), 'Removed sections disappear from the editor');
  root().getElementById('open').click();
  root().getElementById('done').click();
  assert(!root().querySelector('dialog').open, 'Done dismisses the modal');
  return { passed: results.length, results };
};
